import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const failures=[];
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const manifest=JSON.parse(read("public/manifest.webmanifest"));
if(manifest.name!=="Love is Foods")failures.push("manifest name must be Love is Foods");
if(manifest.short_name!=="Love is Foods")failures.push("manifest short name must be Love is Foods");
if(manifest.theme_color!=="#db0b0b")failures.push("manifest theme color must use Love is Foods red");
if(!manifest.icons?.some(icon=>icon.src==="/love-is-foods-icon.svg"))failures.push("Love is Foods app icon missing from manifest");
for(const p of ["/love-is-foods-icon.svg",])if(!manifest.icons?.some(icon=>icon.src===p))failures.push("manifest icon entry missing "+p);
for(const p of ["public/love-is-foods-icon.svg"])if(!fs.existsSync(path.join(root,p)))failures.push("app icon asset missing "+p);
const appManifest=read("src/app/manifest.ts");
if(!appManifest.includes('name: "Love is Foods"')||!appManifest.includes('short_name: "Love is Foods"'))failures.push("Next.js manifest identity is not Love is Foods");
if(!appManifest.includes('theme_color: "#db0b0b"'))failures.push("Next.js manifest theme color is incorrect");
const layout=read("src/app/layout.tsx");
for(const value of ["Love is Foods | Good food, made with love","applicationName:\"Love is Foods\"","capable:true,title:\"Love is Foods\"","themeColor:\"#db0b0b\""])if(!layout.includes(value))failures.push("layout metadata missing "+value);
const sw=read("public/sw.js");
if(!/iteration13-shell-v\\d+/.test(sw))failures.push("service-worker cache namespace must remain isolated and versioned");
if(!sw.includes("/love-is-foods-icon.svg"))failures.push("service-worker app shell must cache the Love is Foods icon");
const pwa=read("src/app/pwa-register.tsx");
for(const value of ['await prompt.prompt()','await prompt.userChoice','className="i13-install-card"','className="i13-install-close"','isIosSafari()','installState === "embedded"','navigator.serviceWorker.register("/sw.js", { updateViaCache: "none" })'])if(!pwa.includes(value))failures.push("protected PWA installation contract missing "+value);
const page=read("src/app/page.tsx");
if(!page.includes("FoodStorefront"))failures.push("homepage must render the Love is Foods storefront");
if(page.includes("Create a new business")||page.includes("Use previous business"))failures.push("generic business setup screen must not be the Love is Foods homepage");
if(failures.length){console.error("LOVE IS FOODS IDENTITY VERIFICATION FAILED");failures.forEach(x=>console.error(" - "+x));process.exit(1)}
console.log("LOVE IS FOODS IDENTITY VERIFIED — brand metadata, app icon, food storefront and protected PWA install lifecycle.");
